// แปลงข้อมูลเป็นรูปแบบ PROVINCES_DATA และเรียงลำดับตามตัวอักษรไทย
const PROVINCES_DATA = Object.keys(SOUTHERN_SCHOOLS_DATA)
  .sort((a, b) => a.localeCompare(b, 'th'))
  .map(prov => ({
    province: prov,
    schools: SOUTHERN_SCHOOLS_DATA[prov]
  }));

// ฟังก์ชันดึงรายชื่อจังหวัดทั้งหมด
function getAllProvinces() {
  return PROVINCES_DATA.map(p => p.province);
}

// ฟังก์ชันดึงรายชื่อโรงเรียนตามจังหวัด
function getSchoolsByProvince(provinceName) {
  if (!provinceName || !SOUTHERN_SCHOOLS_DATA[provinceName]) {
    return [];
  }
  return [...SOUTHERN_SCHOOLS_DATA[provinceName]];
}

